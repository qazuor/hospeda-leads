import { MESSAGE_CATALOG_TEMPLATES, type CatalogTemplate } from "./messageCatalogTemplates";

/** File name of the generated content migration. Applied migrations are checksummed: regenerate only before it ships. */
export const MESSAGE_CATALOG_MIGRATION = "036_message_catalog.sql";

const literal = (value: string | null) => value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`;
const row = (template: CatalogTemplate) =>
  `(${[template.channel, template.name, template.subject, template.body, template.managementType, template.purpose].map(literal).join(",")})`;

/**
 * SQL that replaces every message template and the stored variable settings with the October 2026 catalog.
 * Owner decision (22/10/2026): start from scratch. Sent messages keep their own subject, body and template snapshot;
 * crm_messages.template_id becomes NULL and old template versions are removed with their templates.
 * Deleting the stored variable settings makes the server use the built-in catalog (DEFAULT_MESSAGE_VARIABLES).
 */
export function buildMessageCatalogMigration({ templates = MESSAGE_CATALOG_TEMPLATES }: { templates?: readonly CatalogTemplate[] } = {}): { sql: string } {
  const sql = [
    "-- Message catalog rebuilt from scratch (owner decision 22/10/2026).",
    "-- Generated by scripts/build-message-catalog-migration.ts from src/content/messageCatalogTemplates.ts. Do not edit by hand.",
    "DELETE FROM message_templates;",
    "DELETE FROM app_settings WHERE key='crm_message_variables';",
    "INSERT INTO message_templates(channel,name,subject,body,management_type,purpose) VALUES",
    templates.map(row).join(",\n") + ";",
    "INSERT INTO crm_message_template_versions(template_id,version,snapshot) SELECT id,1,to_jsonb(t) FROM message_templates t;",
    "",
  ].join("\n");
  return { sql };
}
