import { MESSAGE_CATALOG_TEMPLATES, type CatalogTemplate } from "./messageCatalogTemplates";

/** File name of the generated content migration. Applied migrations are checksummed: 036 (October catalog) is applied and must never be rewritten. */
export const MESSAGE_CATALOG_MIGRATION = "058_message_catalog_v3.sql";

const literal = (value: string | null) => value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`;
const row = (template: CatalogTemplate) =>
  `(${[template.channel, template.name, template.subject, template.body, template.managementType, template.purpose, template.vertical].map(literal).join(",")})`;

/**
 * Puts the sales material inside the messages that carry it, as its own paragraph right after «¡Buenísimo, gracias! …».
 * Only email (attached) and WhatsApp resolve material references; Instagram drafts would show the raw token, so the
 * Instagram variant points to the web presentation instead (see messageCatalogTemplates.ts).
 * Resolved by title at apply time; a missing or archived material leaves the message without it instead of failing.
 */
const materialUpdate = (template: CatalogTemplate) => template.material === null || template.channel === "social" ? null :
  `UPDATE message_templates t SET body=regexp_replace(t.body,'(<p>¡Buenísimo, gracias![^<]*</p>)','\\1<p>{{material:'||m.id::text||${template.channel === "email" ? "':attach'" : "''"}||'}}</p>') FROM crm_sales_materials m WHERE t.name=${literal(template.name)} AND m.id=(SELECT id FROM crm_sales_materials WHERE title=${literal(template.material)} AND status='active' ORDER BY created_at LIMIT 1);`;

/**
 * SQL that replaces every message template with the catalog (v3, owner decision 02/11/2026: permission-first first contact,
 * material right after the yes, self sign-up, «Te armamos la ficha» as a rescue). Sent messages keep their own subject,
 * body and template snapshot; old template versions are removed with their templates. Deleting the stored variable
 * settings makes the server use the built-in variables.
 */
export function buildMessageCatalogMigration({ templates = MESSAGE_CATALOG_TEMPLATES }: { templates?: readonly CatalogTemplate[] } = {}): { sql: string } {
  const sql = [
    "-- Message catalog v3 (owner decision 02/11/2026). Replaces the catalog of migration 036.",
    "-- Generated by scripts/build-message-catalog-migration.ts from src/content/messageCatalogTemplates.ts. Do not edit by hand.",
    "DELETE FROM message_templates;",
    "DELETE FROM app_settings WHERE key='crm_message_variables';",
    "INSERT INTO message_templates(channel,name,subject,body,management_type,purpose,vertical) VALUES",
    templates.map(row).join(",\n") + ";",
    ...templates.map(materialUpdate).filter((line): line is string => line !== null),
    "INSERT INTO crm_message_template_versions(template_id,version,snapshot) SELECT id,1,to_jsonb(t) FROM message_templates t;",
    "",
  ].join("\n");
  return { sql };
}
